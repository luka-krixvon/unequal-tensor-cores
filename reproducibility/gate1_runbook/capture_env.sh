echo "  nvlink_status: \"$(nvidia-smi nvlink -s 2>&1 | head -1 | tr -d '\n' | cut -c1-60)\""
echo "  topo_matrix: |"
nvidia-smi topo -m 2>/dev/null | sed 's/^/    /' | head -6
