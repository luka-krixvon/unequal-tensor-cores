echo "  power_limit_w: $(nvidia-smi --query-gpu=power.limit --format=csv,noheader,nounits | head -1)"
echo "  ecc_mode: $(nvidia-smi --query-gpu=ecc.mode.current --format=csv,noheader | head -1)"
echo "  uuid_hashes: [$(nvidia-smi --query-gpu=uuid --format=csv,noheader | while read u; do printf '"%s",' $(echo $u|sha256sum|cut -c1-12); done | sed 's/,$//')]"
