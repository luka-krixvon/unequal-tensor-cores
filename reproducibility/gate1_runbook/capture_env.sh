echo "  kernel: $(uname -r)"
echo "  nvidia_driver: $(nvidia-smi --query-gpu=driver_version --format=csv,noheader | head -1)"
echo "  cuda_driver_api: $(nvidia-smi | sed -n 's/.*CUDA Version: *\([0-9.]*\).*/\1/p' | head -1)"
